async (page) => {
  const checks = [];
  await page.waitForLoadState('networkidle');
  const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  await page.context().grantPermissions(['clipboard-read','clipboard-write'], { origin:new URL(page.url()).origin });
  await page.setViewportSize({width:1440,height:1000});
  const scopeTab = page.getByRole('tab',{name:'Zakres',exact:true});
  await scopeTab.click(); await page.getByRole("tabpanel",{name:"Zakres",exact:true}).waitFor({state:"visible"});
  assert(await scopeTab.getAttribute('aria-selected') === 'true','hero scope tab');
  await scopeTab.press("ArrowRight"); await page.getByRole("tabpanel",{name:"Ustalenia",exact:true}).waitFor({state:"visible"});
  assert(await page.getByRole('tab',{name:'Ustalenia',exact:true}).getAttribute('aria-selected') === 'true','tab arrow navigation');
  await page.locator('#hero-evidence-summary').click();
  assert(await page.locator('.report-preview details').getAttribute('open') !== null,'hero evidence opens');
  await page.getByRole("tab",{name:"Retest",exact:true}).click(); await page.getByRole("heading",{name:"Poprawka potwierdzona."}).waitFor();
  assert(await page.getByRole('heading',{name:'Poprawka potwierdzona.'}).isVisible(),'hero retest panel');
  await page.getByRole('button',{name:'Przejdź do zakresu',exact:true}).click();
  const consent = page.getByRole('checkbox',{name:'Potwierdzam demonstracyjny zakres odczytu.'});
  const approve = page.getByRole('button',{name:'Zatwierdź zakres i zobacz wynik'});
  await consent.waitFor(); assert(await approve.isDisabled(),'demo cannot continue without consent');
  await page.getByRole('button',{name:'Pokaż próbę wyjścia poza zakres'}).click();
  await page.getByText("Zablokowano · poza zatwierdzonym zakresem",{exact:true}).waitFor(); assert(await page.getByText('Zablokowano · poza zatwierdzonym zakresem',{exact:true}).isVisible(),'out of scope refusal');
  await consent.focus();
  await consent.press('Space');
  await approve.click();
  const next = page.getByRole('button',{name:'Zobacz retest po poprawce'});
  await next.waitFor(); assert(await next.isDisabled(),'evidence precedes retest');
  await page.locator('#guided-evidence-summary').focus();
  await page.locator('#guided-evidence-summary').press('Enter');
  await next.click();
  await page.getByRole("heading",{name:"Sprawdź, czy poprawka działa."}).waitFor(); assert(await page.getByText('Potwierdzona poprawka',{exact:true}).first().isVisible(),'full demo confirmed fix');
  await page.getByRole('button',{name:'Porównaj: niepełny raport'}).click();
  await page.getByRole("heading",{name:"Brak wpisu to za mało."}).waitFor(); assert(await page.getByRole('heading',{name:'Brak wpisu to za mało.'}).isVisible(),'partial report stays unconfirmed');
  await page.locator('.guided-demo').screenshot({path:'output/playwright/demo-retest.png'});
  await page.getByRole('button',{name:'Wróć do pełnego retestu'}).click();
  await page.getByRole('button',{name:'Zacznij od nowa'}).click();
  await page.getByRole("heading",{name:"Wybierz punkt startu."}).waitFor(); assert(await page.getByRole('heading',{name:'Wybierz punkt startu.'}).isVisible(),'demo resets');
  await page.getByRole('button',{name:'Skopiuj polecenia Codex',exact:true}).click();
  let clip = await page.evaluate(()=>navigator.clipboard.readText());
  assert(clip.includes('--branch codex/node-v0.1') && clip.endsWith('codex'),'Codex command clipboard');
  await page.getByRole('button',{name:'Skopiuj prompt Codex',exact:true}).click();
  assert(await page.evaluate(()=>navigator.clipboard.readText()) === '$cyber-defense demo','Codex prompt clipboard');
  await page.getByRole('tab',{name:'Claude Code',exact:true}).click();
  await page.getByRole('button',{name:'Skopiuj polecenia Claude Code',exact:true}).click();
  clip = await page.evaluate(()=>navigator.clipboard.readText());
  assert(clip.endsWith('claude') && clip.includes('https://github.com/aievolutionpl/cyber-defense-agent.git'),'Claude command clipboard');
  await page.getByRole('button',{name:'Skopiuj prompt Claude Code',exact:true}).click();
  assert(await page.evaluate(()=>navigator.clipboard.readText()) === '/cyber-defense demo','Claude prompt clipboard');
  await page.getByRole('tab',{name:'Claude Code',exact:true}).press('ArrowLeft');
  assert(await page.getByRole('tab',{name:'Codex',exact:true}).getAttribute('aria-selected') === 'true','install keyboard tabs');
  const faq = page.locator('.faq-list details').first();
  await faq.locator('summary').focus();
  await faq.locator('summary').press('Enter');
  assert(await faq.getAttribute('open') !== null,'FAQ keyboard activation');
  await faq.locator('summary').press('Enter');
  const anchors = await page.evaluate(()=>Array.from(document.querySelectorAll('a[href^="#"]')).map(a=>a.getAttribute('href')).filter(h=>h.length>1&&!document.getElementById(h.slice(1))));
  assert(anchors.length===0,'internal anchors resolve');
  const external = await page.locator('a[href^="https://"]').evaluateAll(as=>as.map(a=>a.getAttribute('href')));
  assert(external.every(h=>h.startsWith('https://github.com/aievolutionpl/cyber-defense-agent/')),'all GitHub buttons use actual repository and branch');
  await page.getByRole('tab',{name:'Ustalenia',exact:true}).click();
  await page.locator('#hero-evidence-summary').click();
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/desktop.png',fullPage:true});
  await page.screenshot({path:'output/playwright/desktop-hero.png'});
  for (const width of [1280,768,390,375,320]) {
    await page.setViewportSize({width,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth), 'no horizontal overflow '+width);
    if(width===390) {
      const menu = page.getByRole('button',{name:'Otwórz nawigację'});
      await menu.focus(); await menu.press('Enter');
      assert(await page.getByRole('navigation',{name:'Nawigacja główna'}).isVisible(),'mobile menu keyboard');
      await page.getByRole('link',{name:'Instalacja',exact:true}).click();
      assert(await page.getByRole('button',{name:'Otwórz nawigację'}).getAttribute('aria-expanded')==='false','mobile menu closes after navigation');
      await page.evaluate(()=>window.scrollTo(0,0));
      await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
      await page.locator('.hero').screenshot({path:'output/playwright/mobile-hero.png'});
    }
  }
  await page.emulateMedia({reducedMotion:'reduce'});
  assert(await page.evaluate(()=>getComputedStyle(document.documentElement).scrollBehavior)==='auto','reduced motion scrolling');
  assert(await page.locator('.button').first().evaluate(el=>getComputedStyle(el).transitionDuration)==='0s','reduced motion transitions');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:1440,height:1000});
  return {passed:checks.length,checks,externalLinks:external};
}
